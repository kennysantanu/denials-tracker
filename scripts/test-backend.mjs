#!/usr/bin/env node
/** Isolated local Supabase lifecycle. Never reads .env or inherits deployment settings. */
import { randomBytes, createHmac, createHash } from 'node:crypto';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import { spawnSync } from 'node:child_process';
import { createServer } from 'node:net';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const project = `denials-tracker-test-${createHash('sha256').update(root).digest('hex').slice(0, 12)}`;
const envPath = resolve(root, '.env.test.local');
const marker = '# denials-tracker disposable test backend v1';
const api = 'http://127.0.0.1:58000';
const origin = 'http://127.0.0.1:4173';
const secret = () => randomBytes(32).toString('hex');
const required = [
	'TEST_BACKEND',
	'PUBLIC_SUPABASE_URL',
	'PUBLIC_SUPABASE_ANON_KEY',
	'SUPABASE_SERVICE_ROLE_KEY',
	'DATABASE_URL',
	'ORIGIN',
	'JWT_SECRET',
	'POSTGRES_PASSWORD',
	'DASHBOARD_PASSWORD',
	'PG_META_CRYPTO_KEY'
];

// Override every app runtime setting, including in environments generated by older versions.
export const appTestEnv = {
	MAX_LOGIN_ATTEMPTS: '100',
	SESSION_TIMEOUT_MINUTES: '30',
	PASSWORD_EXPIRY_DAYS: '90',
	AUTH_COOKIE_SECURE: 'false',
	WIKI_PATH: '',
	SK_ADAPTER: 'node'
};

function jwt(role, key) {
	const encode = (value) => Buffer.from(JSON.stringify(value)).toString('base64url');
	const body = `${encode({ alg: 'HS256', typ: 'JWT' })}.${encode({ role, iss: 'supabase', iat: Math.floor(Date.now() / 1000), exp: Math.floor(Date.now() / 1000) + 315360000 })}`;
	return `${body}.${createHmac('sha256', key).update(body).digest('base64url')}`;
}

/** Load only our marked, fixed-loopback environment; override ambient production values. */
export function loadTestEnv() {
	if (!existsSync(envPath))
		throw new Error(
			'Local test backend not configured. Run node scripts/test-backend.mjs up first.'
		);
	const raw = readFileSync(envPath, 'utf8');
	if (raw.split(/\r?\n/)[0] !== marker) throw new Error('Refusing unmarked test environment file.');
	const env = Object.fromEntries(
		raw
			.split(/\r?\n/)
			.filter((line) => line && !line.startsWith('#'))
			.map((line) => {
				const index = line.indexOf('=');
				if (index < 1) throw new Error('Invalid test environment entry.');
				return [line.slice(0, index), line.slice(index + 1)];
			})
	);
	if (
		required.some((key) => !env[key]) ||
		env.TEST_BACKEND !== 'local' ||
		env.PUBLIC_SUPABASE_URL !== api ||
		env.ORIGIN !== origin ||
		env.SUPABASE_INTERNAL_URL !== api
	)
		throw new Error('Refusing non-local or incomplete test environment.');
	const db = new URL(env.DATABASE_URL);
	if (
		db.protocol !== 'postgres:' ||
		db.hostname !== '127.0.0.1' ||
		db.port !== '55432' ||
		db.pathname !== '/postgres' ||
		db.username !== 'postgres' ||
		db.password !== env.POSTGRES_PASSWORD
	)
		throw new Error('Refusing non-test database URL.');
	for (const role of ['anon', 'service_role']) {
		const key = role === 'anon' ? env.PUBLIC_SUPABASE_ANON_KEY : env.SUPABASE_SERVICE_ROLE_KEY;
		const payload = JSON.parse(Buffer.from(key.split('.')[1] ?? '', 'base64url').toString());
		const signed = key.slice(0, key.lastIndexOf('.'));
		if (
			payload.role !== role ||
			payload.exp <= Date.now() / 1000 ||
			createHmac('sha256', env.JWT_SECRET).update(signed).digest('base64url') !== key.split('.')[2]
		)
			throw new Error('Invalid test JWT.');
	}
	Object.assign(env, appTestEnv);
	Object.assign(process.env, env);
	return env;
}

function generateEnv() {
	const key = secret();
	const password = secret();
	const env = {
		TEST_BACKEND: 'local',
		ORIGIN: origin,
		PUBLIC_SUPABASE_URL: api,
		SUPABASE_INTERNAL_URL: api,
		PUBLIC_SUPABASE_ANON_KEY: jwt('anon', key),
		SUPABASE_SERVICE_ROLE_KEY: jwt('service_role', key),
		JWT_SECRET: key,
		POSTGRES_PASSWORD: password,
		DATABASE_URL: `postgres://postgres:${password}@127.0.0.1:55432/postgres`,
		DASHBOARD_PASSWORD: secret(),
		PG_META_CRYPTO_KEY: secret()
	};
	writeFileSync(
		envPath,
		`${marker}\n${Object.entries(env)
			.map(([k, v]) => `${k}=${v}`)
			.join('\n')}\n`,
		{ mode: 0o600, flag: 'wx' }
	);
}

function compose(args, env, capture = false) {
	// Explicit file/project/env and a clean interpolation environment prevent .env leakage.
	const childEnv = Object.fromEntries(
		Object.entries(process.env).filter(([key]) =>
			/^(PATH|HOME|DOCKER_.*|XDG_.*|TMPDIR|SSH_AUTH_SOCK|USER|COMPOSE_PARALLEL_LIMIT)$/.test(key)
		)
	);
	const result = spawnSync(
		'docker',
		[
			'compose',
			'--project-name',
			project,
			'--env-file',
			envPath,
			'-f',
			resolve(root, 'docker-compose.test.yml'),
			...args
		],
		{
			cwd: root,
			env: { ...childEnv, ...env },
			encoding: 'utf8',
			stdio: capture ? 'pipe' : 'inherit'
		}
	);
	if (result.error) throw result.error;
	if (result.status !== 0)
		throw new Error(`Test compose ${args[0]} failed${capture ? `: ${result.stderr}` : '.'}`);
	return result.stdout;
}

async function assertFree(port) {
	await new Promise((done, reject) => {
		const server = createServer();
		server.once('error', () =>
			reject(new Error(`Reserved test port ${port} is busy; stop its owner before starting tests.`))
		);
		server.listen(port, '127.0.0.1', () => server.close(done));
	});
}

async function main(command) {
	if (!['up', 'down', 'status'].includes(command))
		throw new Error('Usage: node scripts/test-backend.mjs <up|down|status>');
	if (command === 'up' && !existsSync(envPath)) {
		const volumes = spawnSync(
			'docker',
			[
				'volume',
				'ls',
				'--filter',
				`label=com.docker.compose.project=${project}`,
				'--format',
				'{{.Name}}'
			],
			{ encoding: 'utf8' }
		);
		if (volumes.error) throw volumes.error;
		if (volumes.status !== 0)
			throw new Error('Cannot inspect test volumes before generating secrets.');
		if (volumes.stdout.trim())
			throw new Error(
				'Test volumes exist but .env.test.local is missing. Restore that checkout’s secrets file before starting; do not generate new credentials for retained volumes.'
			);
		generateEnv();
	}
	const env = loadTestEnv();
	if (command === 'status') return void compose(['ps', '-a'], env);
	if (command === 'down') return void compose(['down', '--remove-orphans'], env); // Volumes intentionally retained.
	const running = compose(['ps', '--status', 'running', '--services'], env, true).trim();
	await Promise.all([
		...(running.split('\n').includes('kong') ? [] : [assertFree(58000)]),
		...(running.split('\n').includes('db') ? [] : [assertFree(55432)])
	]);
	compose(['up', '-d', '--wait', '--wait-timeout', '180', 'kong', 'imgproxy'], env);
	compose(['run', '--rm', 'migrate'], env);
	const response = await fetch(`${api}/rest/v1/`, {
		headers: { apikey: env.PUBLIC_SUPABASE_ANON_KEY }
	});
	await response.arrayBuffer();
	if (!response.ok) throw new Error(`Local REST readiness failed: ${response.status}`);
	console.log(`Test backend ready: ${api} (app origin ${origin}). Volumes retained by down.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	main(process.argv[2]).catch((error) => {
		console.error(error.message);
		process.exitCode = 1;
	});
}
